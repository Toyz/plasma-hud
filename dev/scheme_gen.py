#!/usr/bin/env python3
"""Generate the Helba World KDE color schemes (dark and light) into packages/color-schemes.

    python3 dev/scheme_gen.py packages/color-schemes

Breeze Dark / Breeze Light are the templates (every group and key KDE expects); the
.hack colors replace their color groups and window-manager colors. The Plasma desktop
theme (helba-hud) paints its frames from these roles: DecorationFocus is the gold trim,
DecorationHover the data cyan.
"""
import os
import sys

OUT = sys.argv[1]


def fg(normal, inactive, active, link, visited, neg, neutral, pos, focus, hover):
    return {
        "ForegroundNormal": normal, "ForegroundInactive": inactive, "ForegroundActive": active,
        "ForegroundLink": link, "ForegroundVisited": visited, "ForegroundNegative": neg,
        "ForegroundNeutral": neutral, "ForegroundPositive": pos,
        "DecorationFocus": focus, "DecorationHover": hover,
    }


def group(bg, alt, f):
    return {"BackgroundNormal": bg, "BackgroundAlternate": alt, **f}


# ------------------------------------------------------------------ dark (The World)
GOLD, CYAN = "184,147,90", "143,227,255"
dark_fg = fg("234,240,251", "141,152,182", CYAN, GOLD, "196,170,110", "255,96,116", "245,200,90", "120,220,160", GOLD, CYAN)
DARK = {
    "Window": group("11,17,38", "16,24,52", dark_fg),
    "View": group("8,13,30", "11,17,38", dark_fg),
    "Button": group("20,28,62", "16,24,52", dark_fg),
    "Header": group("14,21,46", "11,17,38", dark_fg),
    "Header][Inactive": group("11,17,38", "8,13,30", dark_fg),
    "Tooltip": group("11,17,38", "16,24,52", dark_fg),
    "Complementary": group("11,17,38", "16,24,52", dark_fg),
    "Selection": group(CYAN, "120,200,235", fg("10,16,34", "40,60,90", "10,16,34", "90,60,10", "90,70,30", "160,20,50", "120,90,10", "20,100,60", GOLD, CYAN)),
}
DARK_WM = {"activeBackground": "11,17,38", "activeForeground": "234,240,251", "activeBlend": GOLD,
           "inactiveBackground": "8,13,30", "inactiveForeground": "141,152,182", "inactiveBlend": "141,152,182"}

# ------------------------------------------------------------------ light (parchment)
BRONZE, TEAL = "138,100,24", "20,112,138"
light_fg = fg("26,32,51", "90,99,128", TEAL, BRONZE, "110,84,40", "200,30,69", "160,115,8", "30,130,80", BRONZE, TEAL)
LIGHT = {
    "Window": group("243,238,225", "236,229,212", light_fg),
    "View": group("250,247,238", "243,238,225", light_fg),
    "Button": group("236,229,212", "228,220,200", light_fg),
    "Header": group("236,229,212", "243,238,225", light_fg),
    "Header][Inactive": group("243,238,225", "236,229,212", light_fg),
    "Tooltip": group("250,247,238", "243,238,225", light_fg),
    # Complementary stays dark: OSDs and other contrast surfaces.
    "Complementary": DARK["Window"],
    "Selection": group(TEAL, "40,128,152", fg("250,247,238", "200,225,232", "250,247,238", "245,220,160", "230,210,170", "255,190,200", "250,225,150", "190,240,210", BRONZE, TEAL)),
}
LIGHT_WM = {"activeBackground": "236,229,212", "activeForeground": "26,32,51", "activeBlend": BRONZE,
            "inactiveBackground": "243,238,225", "inactiveForeground": "90,99,128", "inactiveBlend": "90,99,128"}


def build(template, name, file, groups, wm):
    lines = open(f"/usr/share/color-schemes/{template}.colors").read().splitlines()
    out, section = [], None
    for line in lines:
        if line.startswith("["):
            section = line
            out.append(line)
            continue
        if "=" not in line or section is None:
            out.append(line)
            continue
        key = line.split("=", 1)[0]
        if key.startswith("Name["):
            continue  # Breeze's translated names
        if section.startswith("[Colors:"):
            g = section[len("[Colors:"):-1]
            if g in groups and key in groups[g]:
                line = f"{key}={groups[g][key]}"
        elif section == "[WM]" and key in wm:
            line = f"{key}={wm[key]}"
        elif section == "[General]" and key == "Name":
            line = f"Name={name}"
        elif section == "[General]" and key == "ColorScheme":
            line = f"ColorScheme={file}"
        out.append(line)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, file + ".colors"), "w") as f:
        f.write("# Generated by dev/scheme_gen.py from Breeze's " + template + " layout.\n")
        f.write("\n".join(out) + "\n")


build("BreezeDark", "Helba World", "HelbaWorld", DARK, DARK_WM)
build("BreezeLight", "Helba World Light", "HelbaWorldLight", LIGHT, LIGHT_WM)
print("color schemes written to", OUT)
